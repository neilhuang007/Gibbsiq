"""Generate brute-force-verifiable ground-truth optimization fixtures.

Every instance produced here is small enough to solve by exhaustive
enumeration, so the optimum, the degeneracy, and a witness state are *proven*
rather than "best known". The output matches the golden-fixture schema used by
``src/gibbsiq/evaluation.py`` so a future Gibbsiq solver can be scored against
these instances with the existing JSON evaluator.

Conventions (do not violate; see reference/08-evaluation/equation-audit.md):
    Ising energy  E(s) = offset + sum_i h_i s_i + sum_{i<j} J_ij s_i s_j,
                  with s_i in {-1, +1} and upper-triangle quadratic terms only.
    Max-Cut       Ising energy = sum_edges s_u s_v; cut = (|E| - energy) / 2.

Provenance: instances are generated by a deterministic, explicitly-seeded PRNG
(`random.Random(seed)`), so the corpus is reproducible from the recorded seed.
A content checksum of the emitted document is printed for artifact tracking.

Usage (PowerShell):
    python tools/generate_ground_truth.py --out OUTPUT.json
"""

