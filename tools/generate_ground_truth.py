def checksum(document: dict[str, Any]) -> str:
    payload = json.dumps(document, sort_keys=True, separators=(",", ":")).encode("utf-8")
    return hashlib.sha256(payload).hexdigest()


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("reference/06-benchmarks/fixtures/ground-truth-small.json"),
        help="Output path for the generated corpus.",
    )
    args = parser.parse_args(argv)

    document = build_corpus()
    document["content_sha256"] = checksum(
        {k: v for k, v in document.items() if k != "content_sha256"}
    )

    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(document, indent=2) + "\n", encoding="utf-8")

    print(f"wrote {len(document['fixtures'])} fixtures to {args.out}")
    print(f"families: {', '.join(document['families'])}")
    print(f"content_sha256: {document['content_sha256']}")
    return 0


